using GameWake.Core.Infrastructure;
using GameWake.Core.Models;
using GameWake.Core.Providers;
using Microsoft.Extensions.Logging;

namespace GameWake.Providers.Simulation;

/// <summary>
/// Development-only scripted launcher (enabled with <c>--simulate</c>). Every operation is marked
/// <see cref="GameOperation.IsSimulated"/>; the sleep policy ignores simulated activity unless
/// <c>--simulate-prevent-sleep</c> is passed.
/// </summary>
public sealed class SimulationProvider : LauncherProviderBase
{
    public static readonly TimeSpan CycleLength = TimeSpan.FromMinutes(8);

    private const long GameASize = 2_500_000_000;
    private const long GameCSize = 860_000_000;
    private const string Detail = "Simulated activity — not a real download";

    private readonly DateTimeOffset _startedAt;

    public SimulationProvider(IClock clock, ILogger<SimulationProvider> logger)
        : base(clock, logger)
    {
        _startedAt = clock.Now;
    }

    public override LauncherKind Launcher => LauncherKind.Simulation;

    protected override ValueTask<LauncherSnapshot> PollCoreAsync(DateTimeOffset now, CancellationToken cancellationToken)
    {
        var elapsed = now - _startedAt;
        var t = TimeSpan.FromTicks(Math.Max(0, elapsed.Ticks) % CycleLength.Ticks).TotalSeconds;
        var operations = Script(t);
        return ValueTask.FromResult(new LauncherSnapshot
        {
            Launcher = LauncherKind.Simulation,
            CheckedAt = now,
            IsInstalled = true,
            IsRunning = true,
            IsSimulated = true,
            StatusDetail = "Simulation mode: none of this activity is real",
            Operations = operations,
            Limitations = ["Simulated data for testing the interface. It never reflects a real launcher."],
            Diagnostics = [$"Simulation cycle position: {t:0} s of {CycleLength.TotalSeconds:0} s"],
        });
    }

    internal static IReadOnlyList<GameOperation> Script(double t)
    {
        var operations = new List<GameOperation>();
        if (t < 150)
        {
            var fraction = t / 150;
            operations.Add(Op("a", "Simulated Game A", ActivityState.Downloading, DetectionConfidence.Confirmed) with
            {
                Progress = fraction,
                ProgressNote = "Simulated",
                TotalBytes = GameASize,
                BytesPerSecond = GameASize / 150.0,
                SpeedNote = "Simulated",
            });
            operations.Add(Op("b", "Simulated Game B", ActivityState.Queued, DetectionConfidence.Inactive));
        }
        else if (t < 200)
        {
            operations.Add(Op("a", "Simulated Game A", ActivityState.Unpacking, DetectionConfidence.Confirmed) with { TotalBytes = GameASize });
            operations.Add(Op("b", "Simulated Game B", ActivityState.Downloading, DetectionConfidence.Probable));
        }
        else if (t < 260)
        {
            operations.Add(Op("a", "Simulated Game A", ActivityState.Completed, DetectionConfidence.Inactive) with { TotalBytes = GameASize });
            operations.Add(Op("b", "Simulated Game B", ActivityState.Downloading, DetectionConfidence.Probable));
        }
        else if (t < 330)
        {
            operations.Add(Op("b", "Simulated Game B", ActivityState.Paused, DetectionConfidence.Inactive));
            operations.Add(Op("c", "Simulated Game C", ActivityState.Verifying, DetectionConfidence.Confirmed) with
            {
                Progress = (t - 260) / 70,
                ProgressNote = "Simulated",
                TotalBytes = GameCSize,
            });
        }
        else if (t < 360)
        {
            operations.Add(Op("c", null, ActivityState.Unknown, DetectionConfidence.Unknown) with
            {
                TitleNote = "Simulated missing title",
                StateDetail = "Simulated stale signal",
            });
        }

        return operations;
    }

    private static GameOperation Op(string id, string? title, ActivityState state, DetectionConfidence confidence) => new()
    {
        Key = $"simulation:{id}",
        Launcher = LauncherKind.Simulation,
        GameId = $"sim-{id}",
        GameTitle = title,
        State = state,
        Confidence = confidence,
        EvidenceKind = EvidenceKind.Direct,
        StateDetail = Detail,
        Evidence = ["Generated by the simulation script"],
        IsSimulated = true,
    };
}
